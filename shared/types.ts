// Shared contract between the browser sync engine (src/sync) and the server
// (server/src). See docs/backend/SPEC.md. Builders: implement against these
// types; change them only with the orchestrator's agreement.

// ── Synced rows ─────────────────────────────────────────────────────────
// Field names deliberately match the old InstantDB attributes so the UI
// needs minimal changes. Optional fields are absent or null when unset.

export type PlayerRow = {
  id: string;
  name: string;
  claimedBy?: string | null; // user id of the account/phone that is this player
  mergedInto?: string | null; // player id this one was merged into
  mergedAt?: string | null; // ISO
  mergeLog?: MergeLog | null;
  createdAt?: string | null; // ISO (absent on rows imported from InstantDB)
};

export type MergeLog = {
  into: string;
  seats: string[]; // seat ids moved
  turns: string[]; // turn ids moved
  dealerGames: string[]; // game ids whose initialDealerId moved
};

export type GameRow = {
  id: string;
  createdAt: string; // ISO
  createdBy: string; // user id
  deletedAt?: string | null; // ISO; soft delete
  initialDealerId?: string | null; // player id
};

// "playersOrders" in the old schema.
export type SeatRow = {
  id: string;
  gameId: string;
  playerId: string;
  orderNumber: number;
};

export type RoundRow = {
  id: string;
  gameId: string;
  roundNumber: number; // 0..12, index into DEALS
};

export type TurnRow = {
  id: string;
  roundId: string;
  playerId: string;
  bid?: number | null;
  score?: number | null;
};

export type Tables = {
  players: PlayerRow;
  games: GameRow;
  seats: SeatRow;
  rounds: RoundRow;
  turns: TurnRow;
};
export type TableName = keyof Tables;
export const TABLES: TableName[] = [
  "players",
  "games",
  "seats",
  "rounds",
  "turns",
];

// A complete set of rows, keyed by id. The client keeps one of these (the
// server snapshot) and the server exposes its SQLite data through ReadState.
export type DataState = { [T in TableName]: Map<string, Tables[T]> };

// Read access used by actions. Implemented over an in-memory DataState on
// the client and over SQLite on the server.
export interface ReadState {
  get<T extends TableName>(table: T, id: string): Tables[T] | undefined;
  // All rows in `table` whose `field` equals `value` (e.g. seats by gameId).
  where<T extends TableName, K extends keyof Tables[T]>(
    table: T,
    field: K,
    value: Tables[T][K]
  ): Tables[T][];
}

// ── Row operations produced by actions ──────────────────────────────────

export type RowOp =
  | { op: "put"; table: TableName; row: Tables[TableName] } // insert or replace whole row
  | { op: "delete"; table: TableName; id: string };

// ── Actions ─────────────────────────────────────────────────────────────
// Every write in the app is one of these. Ids for new rows are generated by
// the client (crypto.randomUUID) so actions are idempotent and work offline.

export type ActionArgs = {
  createPlayer: { playerId: string; name: string; claim?: boolean };
  claimPlayer: { playerId: string };
  unclaimPlayer: { playerId: string };
  // Creates the game, its 13 rounds and the host's seat (order 0).
  createGame: {
    gameId: string;
    roundIds: string[];
    seatId: string;
    playerId: string;
  };
  deleteGame: { gameId: string };
  addSeat: {
    seatId: string;
    gameId: string;
    playerId: string;
    orderNumber: number;
  };
  removeSeat: { seatId: string };
  reorderSeats: { gameId: string; seatIds: string[] }; // new order, all seats
  setInitialDealer: { gameId: string; playerId: string };
  placeBid: { turnId: string; roundId: string; playerId: string; bid: number };
  setScore: { turnId: string; score: number };
  clearScore: { turnId: string };
  deleteTurn: { turnId: string };
  mergePlayers: { fromId: string; intoId: string };
  undoMerge: { fromId: string };
  // Upload of a local (offline guest-mode) game; see GuestMigrationDialog.
  importGame: {
    game: GameRow;
    newPlayers: { id: string; name: string }[];
    seats: SeatRow[];
    rounds: RoundRow[];
    turns: TurnRow[];
  };
};
export type ActionName = keyof ActionArgs;

export type Action<N extends ActionName = ActionName> = {
  id: string; // uuid, for idempotency
  name: N;
  args: ActionArgs[N];
  clientTime?: string; // ISO, informational
};

export type ActionContext = {
  userId: string | null; // null = signed out (cannot write)
  isGuest: boolean;
  now: string; // ISO timestamp to stamp createdAt/mergedAt etc.
  // Server-only: lets the guest → account handoff merge a player that is
  // claimed by the (former) guest user. Never set from client input.
  internal?: { allowClaimedFrom?: string };
};

export class ActionError extends Error {
  constructor(message: string, public code: string = "rejected") {
    super(message);
  }
}

// Thrown by a ReadState implementation when storage itself fails (e.g. the
// database is locked). applyAction re-throws it untouched so the server can
// answer "try again" instead of rejecting the action for good.
export class StateError extends Error {}

// Implemented in shared/actions.ts:
//   export function applyAction(state: ReadState, action: Action, ctx: ActionContext): RowOp[]
// Pure and deterministic: throws ActionError when not allowed/invalid,
// otherwise returns the row ops to apply. Must not mutate `state`.

// ── Users (server only, never synced) ───────────────────────────────────

export type PublicUser = {
  id: string;
  email: string | null;
  isGuest: boolean;
};

// ── HTTP API payloads (prefix /contract-whist/api) ──────────────────────

export type AuthResponse = { token: string; user: PublicUser };

export type ChangeSet = {
  version: number; // server version after these changes
  // Upserted rows (full rows) and deleted ids, per table.
  puts: Partial<{ [T in TableName]: Tables[T][] }>;
  deletes: Partial<Record<TableName, string[]>>;
  // True when this is a full snapshot (client should replace its data).
  reset?: boolean;
};

export type PushRequest = { actions: Action[] };
export type PushResult =
  | { id: string; ok: true }
  | { id: string; ok: false; error: string; code: string };
export type PushResponse = { results: PushResult[]; version: number };
